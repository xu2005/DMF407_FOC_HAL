"""Regenerate host fixtures from frozen Legacy, never from Motion code.

Run from repo root with Python and native gcc. The added capacity guard aborts
instead of overflowing the legacy array; it does not change valid-domain math.
"""
import hashlib
import pathlib
import re
import subprocess

root = pathlib.Path(__file__).resolve().parents[1]
legacy = root / "Legacy/Template222_A/USER/main.c"
source = legacy.read_bytes().decode("latin1")
start = source.index("void cul_Saccdec(void){")
level = 0
for end in range(source.index("{", start), len(source)):
    level += (source[end] == "{") - (source[end] == "}")
    if level == 0:
        break
function = source[start:end + 1]
function = re.sub(r"//[^\n]*|/\*.*?\*/", "", function, flags=re.S)
function = function.replace("DEC_ACC_PERiod[accCout]=period;",
                            "if(accCout>=Array_LENGTH) exit(2);\nDEC_ACC_PERiod[accCout]=period;")
work = root / "build/v22-vectors"
work.mkdir(parents=True, exist_ok=True)
c = work / "legacy_profile.c"
c.write_text("""#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <math.h>
typedef uint8_t u8;
#define Array_LENGTH 3000
#define m_streditMotorStep 1.8
#define m_ieditMotordiv 16
#define m_ieditSlineK 4
uint16_t DEC_ACC_PERiod[3001];
long speed_period_min,speed_period_max,dec_len,Position_Limit=1000;
int show_speed;
""" + function + """
int main(int argc, char **argv) {
  if(argc!=2) return 1;
  show_speed=atoi(argv[1]); cul_Saccdec();
  printf("%ld\\n",dec_len);
  for(int i=0;i<=dec_len;i++) printf("%u,",DEC_ACC_PERiod[i]);
  return 0;
}
""", encoding="utf-8")
exe = work / "legacy_profile.exe"
subprocess.run(["gcc", "-std=c11", "-O0", str(c), "-lm", "-o", str(exe)], check=True)
parts = ["/* Generated by scripts/freeze_motion_vectors.py from Legacy main.c.",
         f" * Source SHA256: {hashlib.sha256(legacy.read_bytes()).hexdigest()}",
         " * Default step=1.8, div=16, flexibility=4, Vmin=1, Tmax=300, limit=1000. */",
         "#include <stdint.h>"]
entries = []
for speed in (0, 1, 200, 1000):
    count_line, table_line = subprocess.check_output([str(exe), str(speed)], text=True).splitlines()
    values = [int(x) for x in table_line.rstrip(",").split(",")]
    assert len(values) == int(count_line) + 1
    parts.append(f"static const uint16_t legacy_profile_{speed}[] = {{")
    for offset in range(0, len(values), 16):
        parts.append("    " + ", ".join(map(str, values[offset:offset+16])) + ",")
    parts.append("};")
    entries.append(f"    {{{speed}, {count_line}, legacy_profile_{speed}}},")
    print(f"Legacy speed={speed}: {count_line} samples + terminal")
parts += ["static const struct { int32_t speed; uint32_t count; const uint16_t *period; } legacy_profiles[] = {",
          *entries, "};", ""]
destination = root / "tests/host/vectors/motion_profile_legacy.h"
destination.parent.mkdir(parents=True, exist_ok=True)
destination.write_text("\n".join(parts), encoding="utf-8")
